import type { Catalog, Question, QuestionPoints, QuestionSection } from '@/domain/types';

const VERSION = 'placeholder-1';

type Pair = [de: string, en: string];
type OptionSpec = [de: string, en: string, correct: boolean];

function mc(
  id: string,
  topicId: string,
  section: QuestionSection,
  points: QuestionPoints,
  prompt: Pair,
  options: OptionSpec[],
  explanation: Pair,
  variantOf?: string,
): Question {
  return {
    id,
    catalogVersion: VERSION,
    topicId,
    section,
    classes: ['B'],
    points,
    kind: 'multiple-choice',
    prompt: { de: prompt[0], en: prompt[1] },
    options: options.map(([de, en, correct], i) => ({
      id: `${id}-${String.fromCharCode(97 + i)}`,
      text: { de, en },
      correct,
    })),
    explanation: { de: explanation[0], en: explanation[1] },
    variantOf,
  };
}

function num(
  id: string,
  topicId: string,
  section: QuestionSection,
  points: QuestionPoints,
  prompt: Pair,
  value: number,
  unit: Pair,
  explanation: Pair,
  variantOf?: string,
): Question {
  return {
    id,
    catalogVersion: VERSION,
    topicId,
    section,
    classes: ['B'],
    points,
    kind: 'number',
    prompt: { de: prompt[0], en: prompt[1] },
    numberAnswer: { value, unit: { de: unit[0], en: unit[1] } },
    explanation: { de: explanation[0], en: explanation[1] },
    variantOf,
  };
}

